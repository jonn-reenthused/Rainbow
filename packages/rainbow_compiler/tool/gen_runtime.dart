// Regenerate lib/runtime_bundle.dart from the ../../runtime/<platform>/*.asm
// files. Run from the package root:  dart tool/gen_runtime.dart
//
// runtime/<dir>/ holds per-platform modules keyed by the map value
// (runtime/c64/ -> 'cbm' — the key runtimeModules is looked up by).
// runtime/shared/ is Z80 arithmetic merged into the Z80 platforms only.
import 'dart:io';

/// runtime dir -> runtimeModules key (TargetFamily name).
const platforms = {'zx': 'zx', 'cpc': 'cpc', 'c64': 'cbm'};

/// Dirs whose modules are Z80 — runtime/shared/ merges into these.
const z80Dirs = {'zx', 'cpc'};

void main() {
  var dir = Directory('../../runtime');
  if (!dir.existsSync()) dir = Directory('runtime');
  if (!dir.existsSync()) {
    stderr.writeln('runtime/ directory not found');
    exit(1);
  }

  String moduleName(File f) {
    final last = f.uri.pathSegments.last;
    return last
        .replaceAll('rbt_', '')
        .replaceAll(RegExp(r'\.(asm|s)$'), '');
  }

  Map<String, String> readModules(Directory d) {
    if (!d.existsSync()) return {};
    final files = d
        .listSync()
        .whereType<File>()
        .where((f) => f.path.endsWith('.asm') || f.path.endsWith('.s'))
        .toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    return {for (final f in files) moduleName(f): f.readAsStringSync()};
  }

  final shared = readModules(Directory('${dir.path}/shared'));

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_runtime.dart - do not edit')
    ..writeln('/// Runtime asm module sources, per platform')
    ..writeln('/// (runtime/<platform> + runtime/shared merged). Keyed')
    ..writeln('/// by platform then module name (file name without')
    ..writeln('/// the rbt_ prefix and .asm extension).')
    ..writeln(
        'const Map<String, Map<String, String>> runtimeModules = {');

  var count = 0;
  for (final e in platforms.entries) {
    final mods = {
      if (z80Dirs.contains(e.key)) ...shared,
      ...readModules(Directory('${dir.path}/${e.key}')),
    };
    out.writeln("  '${e.value}': {");
    for (final e in mods.entries) {
      count++;
      out.writeln("    '${e.key}': r'''");
      out.write(e.value);
      out.writeln("''',");
    }
    out.writeln('  },');
  }
  out.writeln('};');

  File('lib/runtime_bundle.dart').writeAsStringSync(out.toString());
  print('wrote lib/runtime_bundle.dart ($count modules incl. shared)');
}
